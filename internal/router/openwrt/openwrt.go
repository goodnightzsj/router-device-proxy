package openwrt

import (
	"context"
	"fmt"
	"net"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/goodnightzsj/router-device-proxy/internal/device"
	"github.com/goodnightzsj/router-device-proxy/internal/policy"
	"github.com/goodnightzsj/router-device-proxy/internal/sshx"
)

type Adapter struct {
	SSH          *sshx.Client
	LeaseFile    string
	ConfDir      string
	TmpDir       string
	RestartCmd   string
	ProxyGateway string
}

func (a *Adapter) Devices(ctx context.Context) ([]device.Device, error) {
	leases, err := a.SSH.Run("cat " + sshx.Quote(a.LeaseFile) + " 2>/dev/null")
	if err != nil {
		return nil, err
	}
	neigh, _ := a.SSH.Run("ip neigh 2>/dev/null")
	arp, _ := a.SSH.Run("cat /proc/net/arp 2>/dev/null")

	online := map[string]bool{}
	neighIP := map[string]string{}
	for _, line := range strings.Split(neigh, "\n") {
		f := strings.Fields(line)
		if len(f) < 5 || f[3] != "lladdr" {
			continue
		}
		if ip := net.ParseIP(f[0]); ip == nil || ip.To4() == nil {
			continue
		}
		mac := strings.ToLower(f[4])
		state := strings.ToUpper(f[len(f)-1])
		neighIP[mac] = f[0]
		if state == "REACHABLE" || state == "STALE" || state == "DELAY" || state == "PROBE" {
			online[mac] = true
		}
	}
	for _, line := range strings.Split(arp, "\n") {
		f := strings.Fields(line)
		if len(f) < 6 || f[0] == "IP" {
			continue
		}
		if ip := net.ParseIP(f[0]); ip == nil || ip.To4() == nil {
			continue
		}
		mac := strings.ToLower(f[3])
		if !device.ValidMAC(mac) {
			continue
		}
		if _, ok := neighIP[mac]; !ok {
			neighIP[mac] = f[0]
		}
		if strings.EqualFold(f[2], "0x2") {
			online[mac] = true
		}
	}

	now := time.Now().Unix()
	seen := map[string]bool{}
	out := make([]device.Device, 0, 32)
	for _, line := range strings.Split(leases, "\n") {
		f := strings.Fields(line)
		if len(f) < 4 {
			continue
		}
		exp, _ := strconv.ParseInt(f[0], 10, 64)
		mac := strings.ToLower(f[1])
		if !device.ValidMAC(mac) {
			continue
		}
		ip := f[2]
		name := f[3]
		if name == "*" || name == "" {
			name = mac
		}
		isOnline := exp == 0 || exp > now || online[mac]
		out = append(out, a.finish(device.New(mac, name, ip, isOnline, "lease")))
		seen[mac] = true
	}
	for mac, ip := range neighIP {
		if seen[mac] {
			continue
		}
		out = append(out, a.finish(device.New(mac, mac, ip, online[mac], "neigh")))
	}
	return out, nil
}

func (a *Adapter) finish(d device.Device) device.Device {
	if a.ProxyGateway != "" && d.IP == a.ProxyGateway {
		if d.Type == "unknown" {
			d.Type = "router"
		}
		if d.Name == "" || d.Name == d.MAC {
			if ipLocal(d.IP) {
				if h, err := os.Hostname(); err == nil && usableHostname(h) {
					d.Name = h
				}
			}
		}
	}
	return d
}

func (a *Adapter) Apply(ctx context.Context, policies map[string]policy.Policy) (string, error) {
	// Without a gateway the dhcp-option lines would be emitted empty and the
	// tagged devices would silently keep the router's default path.
	if a.ProxyGateway == "" {
		return "", fmt.Errorf("代理网关未配置，请先在设置里填写旁路由地址")
	}
	content := renderDnsmasq(policies, a.ProxyGateway)
	if err := ctx.Err(); err != nil {
		return "", err
	}
	conf := sshx.Quote(a.ConfDir)
	tmp := sshx.Quote(a.TmpDir)
	script := fmt.Sprintf(`set -e
mkdir -p %s %s
cat > %s/proxy.conf <<'RDP_EOF'
%sRDP_EOF
cp -f %s/proxy.conf %s/proxy.conf
chmod 644 %s/proxy.conf %s/proxy.conf
%s
`, conf, tmp, conf, content, conf, tmp, conf, tmp, a.RestartCmd)
	return a.SSH.Run(script)
}

func (a *Adapter) Install(ctx context.Context) (string, error) {
	if err := ctx.Err(); err != nil {
		return "", err
	}
	conf := sshx.Quote(a.ConfDir)
	tmp := sshx.Quote(a.TmpDir)
	script := fmt.Sprintf(`set -e
mkdir -p %s
cat > %s/restore.sh <<'RDP_EOF'
#!/bin/sh
mkdir -p %s
cp -f %s/*.conf %s/ 2>/dev/null
%s
RDP_EOF
chmod +x %s/restore.sh
uci set firewall.router_device_proxy=include
uci set firewall.router_device_proxy.type=script
uci set firewall.router_device_proxy.path=%s/restore.sh
uci set firewall.router_device_proxy.enabled=1
uci commit firewall
/etc/init.d/firewall restart
`, conf, conf, tmp, conf, tmp, a.RestartCmd, conf, conf)
	return a.SSH.Run(script)
}

func (a *Adapter) OK(ctx context.Context) bool {
	return a.SSH.OK()
}

func (a *Adapter) Test(ctx context.Context) (string, error) {
	out, err := a.SSH.Run("echo ROUTER_DEVICE_PROXY_OK")
	return strings.TrimSpace(out), err
}

func renderDnsmasq(policies map[string]policy.Policy, gateway string) string {
	var b strings.Builder
	b.WriteString("# generated by router-device-proxy; do not edit\n")
	for mac, p := range policies {
		if p.Mode != "proxy" || !device.ValidMAC(mac) {
			continue
		}
		if p.IP != "" && net.ParseIP(p.IP) != nil {
			fmt.Fprintf(&b, "dhcp-host=%s,set:proxy,%s\n", strings.ToLower(mac), p.IP)
		} else {
			fmt.Fprintf(&b, "dhcp-host=%s,set:proxy\n", strings.ToLower(mac))
		}
	}
	fmt.Fprintf(&b, "dhcp-option=tag:proxy,3,%s\n", gateway)
	fmt.Fprintf(&b, "dhcp-option=tag:proxy,6,%s\n", gateway)
	return b.String()
}

func ipLocal(ip string) bool {
	addrs, err := net.InterfaceAddrs()
	if err != nil {
		return false
	}
	for _, addr := range addrs {
		if ipnet, ok := addr.(*net.IPNet); ok && ipnet.IP.String() == ip {
			return true
		}
	}
	return false
}

func usableHostname(h string) bool {
	h = strings.TrimSpace(h)
	if h == "" || h == "localhost" {
		return false
	}
	if len(h) == 12 {
		if _, err := strconv.ParseUint(h, 16, 64); err == nil {
			return false
		}
	}
	return true
}
