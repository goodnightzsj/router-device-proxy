package main

import (
	"encoding/json"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
)

var macRe = regexp.MustCompile(`^([0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}$`)

func validMAC(s string) bool { return macRe.MatchString(s) }
func validIP(s string) bool  { return net.ParseIP(s) != nil }

type Policy struct {
	Mode string `json:"mode"`
	IP   string `json:"ip,omitempty"`
	Name string `json:"name,omitempty"`
}

type Store struct {
	mu      sync.Mutex
	path    string
	Devices map[string]Policy `json:"devices"`
}

func NewStore(path string) *Store {
	return &Store{path: path, Devices: map[string]Policy{}}
}

func (s *Store) Load() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	b, err := os.ReadFile(s.path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if len(b) == 0 {
		return nil
	}
	var raw struct {
		Devices map[string]Policy `json:"devices"`
	}
	if err := json.Unmarshal(b, &raw); err != nil {
		return err
	}
	if raw.Devices != nil {
		s.Devices = raw.Devices
	}
	return nil
}

func (s *Store) saveLocked() error {
	b, err := json.MarshalIndent(struct {
		Devices map[string]Policy `json:"devices"`
	}{Devices: s.Devices}, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(s.path), 0700); err != nil {
		return err
	}
	tmp := s.path + ".tmp"
	if err := os.WriteFile(tmp, b, 0600); err != nil {
		return err
	}
	return os.Rename(tmp, s.path)
}

func (s *Store) SetMode(mac, mode string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	mac = strings.ToLower(mac)
	p := s.Devices[mac]
	p.Mode = mode
	s.Devices[mac] = p
	return s.saveLocked()
}

func (s *Store) SetDevice(mac, mode, ip, name string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	mac = strings.ToLower(mac)
	s.Devices[mac] = Policy{Mode: mode, IP: ip, Name: name}
	return s.saveLocked()
}

func (s *Store) Get(mac string) (Policy, bool) {
	s.mu.Lock()
	defer s.mu.Unlock()
	p, ok := s.Devices[strings.ToLower(mac)]
	return p, ok
}

func (s *Store) All() map[string]Policy {
	s.mu.Lock()
	defer s.mu.Unlock()
	out := make(map[string]Policy, len(s.Devices))
	for k, v := range s.Devices {
		out[k] = v
	}
	return out
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func (a *App) renderDnsmasq() string {
	var b strings.Builder
	b.WriteString("# generated by router-device-proxy; do not edit\n")
	for mac, p := range a.store.All() {
		if p.Mode != "proxy" || !validMAC(mac) {
			continue
		}
		if p.IP != "" && validIP(p.IP) {
			fmt.Fprintf(&b, "dhcp-host=%s,set:proxy,%s\n", strings.ToLower(mac), p.IP)
		} else {
			fmt.Fprintf(&b, "dhcp-host=%s,set:proxy\n", strings.ToLower(mac))
		}
	}
	fmt.Fprintf(&b, "dhcp-option=tag:proxy,3,%s\n", a.cfg.ProxyGateway)
	fmt.Fprintf(&b, "dhcp-option=tag:proxy,6,%s\n", a.cfg.ProxyGateway)
	return b.String()
}

func (a *App) applyPolicy() (string, error) {
	content := a.renderDnsmasq()
	conf := shellQuote(a.cfg.ConfDir)
	tmp := shellQuote(a.cfg.TmpDir)
	script := fmt.Sprintf(`set -e
mkdir -p %s %s
cat > %s/proxy.conf <<'RDP_EOF'
%sRDP_EOF
cp -f %s/proxy.conf %s/proxy.conf
chmod 644 %s/proxy.conf %s/proxy.conf
%s
`, conf, tmp, conf, content, conf, tmp, conf, tmp, a.cfg.RestartCmd)
	return a.sshRun(script)
}

func (a *App) installHook() (string, error) {
	conf := shellQuote(a.cfg.ConfDir)
	tmp := shellQuote(a.cfg.TmpDir)
	script := fmt.Sprintf(`set -e
mkdir -p %s
cat > %s/restore.sh <<'RDP_EOF'
#!/bin/sh
mkdir -p %s
cp -f %s/*.conf %s/ 2>/dev/null
%s
RDP_EOF
chmod +x %s/restore.sh
uci set firewall.router_device_proxy=include
uci set firewall.router_device_proxy.type=script
uci set firewall.router_device_proxy.path=%s/restore.sh
uci set firewall.router_device_proxy.enabled=1
uci commit firewall
/etc/init.d/firewall restart
`, conf, conf, tmp, conf, tmp, a.cfg.RestartCmd, conf, conf)
	return a.sshRun(script)
}
